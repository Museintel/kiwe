const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..'),toolkit=path.join(root,'kiwe-ai-toolkit');
const Ajv=require(require.resolve('ajv/dist/2020',{paths:[toolkit]})).default;
const standalone=require(require.resolve('ajv/dist/standalone',{paths:[toolkit]})).default;
const ajv=new Ajv({allErrors:true,strict:false,code:{source:true}}),ids={},hashes={};
for(const [key,name]of [['discovery','ideate-discovery.schema.json'],['receipt','preview-receipt.schema.json']]){
 const data=Buffer.from(fs.readFileSync(path.join(toolkit,'schemas',name),'utf8').replace(/\r\n?/g,'\n')),schema=JSON.parse(data);
 ajv.addSchema(schema);ids[key]=schema.$id;hashes[name]=crypto.createHash('sha256').update(data).digest('hex');
}
let code=standalone(ajv,ids);
code=code.replaceAll('require("ajv/dist/runtime/ucs2length").default','kiweCodepointLength');
if(/\brequire\s*\(/.test(code))throw Error('New external schema helper requires an explicit portable implementation.');
const out='/* Generated by build-authoring-schemas.cjs; full JSON Schema validators, no runtime dependencies. */\nfunction kiweCodepointLength(value){return Array.from(value).length;}\n'+code+'\nexports.sourceSchemaHashes='+JSON.stringify(hashes)+';\n';
const target=path.join(toolkit,'lib/authoring-schemas.cjs');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==out)throw Error('Generated authoring schemas are stale.');console.log('Authoring schema source parity: PASS');}
else{fs.writeFileSync(target,out);console.log('Built dependency-free authoring schema validators.');}
